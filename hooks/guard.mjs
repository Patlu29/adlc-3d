// PreToolUse guard for Write, Edit and MultiEdit in an ADLC project.
// Denies writes the team's rules forbid outright. Ownership between agents is only a warning,
// given after the edit by review.mjs.

import { SECRET_ENV, agentName, emit, failOpen, findProjectRoot, findSecret, hooksDisabled, newText, readInput } from "./lib.mjs";

// Paths relative to the project root. Generated or user-owned, so never hand-edited.
const BLOCKED_PATHS = [
  [/^(dist|dist-test|node_modules|coverage|playwright-report|test-results)\//, "is generated output. Change the source and rebuild instead"],
  [/^package-lock\.json$/, "is generated by npm. The architect changes dependencies with npm, which regenerates it"],
  [/^assets\/source\//, "belongs to the user and is read only for every agent. Put processed assets under public/"],
];


// Read only for every agent; only the Tech Lead (the main thread) writes these.
const TECH_LEAD_ONLY = /^docs\/(project-status\.md$|lifecycle\/|tracker\/|incidents\/)/;

// Test fixtures may hold throwaway keys, such as a PEM used to test an upload parser.
const FIXTURES = /^tests\/(?:.+\/)?fixtures\//;

function deny(reason) {
  emit("PreToolUse", { permissionDecision: "deny", permissionDecisionReason: `adlc-3d guard: ${reason}` });
}

export function check(input) {
  const toolInput = input && input.tool_input;
  const located = findProjectRoot(toolInput && toolInput.file_path, input && input.cwd);
  if (!located || hooksDisabled(located.root)) return null;
  // macOS and Windows file systems ignore case, so ".ENV" is the same file as ".env" there.
  const caseless = process.platform === "darwin" || process.platform === "win32";
  const rel = caseless ? located.rel.toLowerCase() : located.rel;

  for (const [pattern, why] of BLOCKED_PATHS) if (pattern.test(rel)) return `${rel} ${why}.`;

  if (SECRET_ENV.test(rel))
    return `${rel} holds secret values and must not be written by an agent. Add the variable name to .env.example and list it in docs/deployment.md; the user sets the value.`;

  const agent = agentName(input);
  if (agent && TECH_LEAD_ONLY.test(rel))
    return `${rel} is written only by the Tech Lead. Put what you need recorded in your handoff note.`;

  if (!FIXTURES.test(rel)) {
    const text = newText(toolInput);
    const label = findSecret(text, rel);
    if (label)
      return `the new content for ${rel} contains what looks like ${label}. Never write credentials into the project: read them from the environment and list the variable name in .env.example. If this is a false positive, use an obviously fake value.`;
  }
  return null;
}

if (process.argv[1]?.endsWith("guard.mjs")) {
  await failOpen(async () => {
    const reason = check(await readInput());
    if (reason) deny(reason);
  });
}
