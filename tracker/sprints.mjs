// Sprint arithmetic: local dates, the burndown derived from each card's state history, and velocity.
// One sprint is one ADLC iteration. Cards count as completed once they are ready for release or done.

export const COMPLETED = new Set(["ready_for_release", "done"]);
const DAY_MS = 24 * 60 * 60 * 1000;

// YYYY-MM-DD in the machine's time zone, so a 9 am move in Australia is not filed under yesterday.
export function localDate(value) {
  return new Date(value).toLocaleDateString("en-CA");
}

export function isDate(text) {
  return /^\d{4}-\d{2}-\d{2}$/.test(String(text)) && !Number.isNaN(Date.parse(`${text}T00:00:00`));
}

export function days(start, end) {
  const out = [];
  for (let t = Date.parse(`${start}T12:00:00`); localDate(t) <= end; t += DAY_MS) out.push(localDate(t));
  return out;
}

// The card's state at the end of a day, from its history of { state, at }.
export function stateOn(entry, day) {
  let state = null;
  for (const step of entry?.history || []) if (localDate(step.at) <= day) state = step.state;
  return state ?? entry?.history?.[0]?.state ?? entry?.state ?? "backlog";
}

// Which cards were in the sprint at the end of a day, applying add and drop events in order.
export function scopeOn(sprint, day) {
  const scope = new Set(Object.keys(sprint.committed));
  for (const event of sprint.scope || []) {
    if (localDate(event.at) > day) continue;
    if (event.change === "add") scope.add(event.id);
    else scope.delete(event.id);
  }
  return scope;
}

export function pointsIn(sprint, id) {
  if (id in sprint.committed) return sprint.committed[id];
  const added = (sprint.scope || []).filter((e) => e.id === id && e.change === "add").pop();
  return added ? added.points : 0;
}

export function burndown(sprint, cards, today) {
  const last = today < sprint.end ? today : sprint.end;
  const all = days(sprint.start, sprint.end);
  const committed = Object.values(sprint.committed).reduce((a, b) => a + b, 0);
  return days(sprint.start, last).map((day) => {
    const scope = scopeOn(sprint, day);
    let remaining = 0;
    for (const id of scope) if (!COMPLETED.has(stateOn(cards[id], day))) remaining += pointsIn(sprint, id);
    const elapsed = all.indexOf(day);
    const ideal = all.length > 1 ? Math.max(0, committed - (committed * elapsed) / (all.length - 1)) : 0;
    return { day, remaining, ideal: Math.round(ideal * 10) / 10 };
  });
}

// Mean completed points of the last three closed sprints that committed any points. Bug-fix and
// operations iterations often carry no points and would drag the mean down.
export function velocity(sprints) {
  const closed = Object.values(sprints || {})
    .filter((s) => s.closed && Object.values(s.committed).reduce((a, b) => a + b, 0) > 0)
    .sort((a, b) => a.number - b.number)
    .slice(-3);
  if (!closed.length) return null;
  return Math.round((closed.reduce((sum, s) => sum + s.closed.completed, 0) / closed.length) * 10) / 10;
}

export function renderSprintReport(sprint, cards, { today, velocityValue }) {
  // A closed sprint is reported as it stood on the day it closed.
  const asOf = sprint.closed ? localDate(sprint.closed.at) : today;
  const scope = scopeOn(sprint, asOf);
  const committed = Object.values(sprint.committed).reduce((a, b) => a + b, 0);
  let inScope = 0;
  let completed = 0;
  const byState = {};
  for (const id of scope) {
    const points = pointsIn(sprint, id);
    const state = sprint.closed ? stateOn(cards[id], asOf) : cards[id]?.state || "backlog";
    inScope += points;
    if (COMPLETED.has(state)) completed += points;
    (byState[state] ||= []).push(id);
  }
  const lines = [
    `# Sprint ${sprint.number}`,
    "",
    "Generated by the adlc-3d tracker. Do not edit; run `sprint report` again.",
    "",
    `Goal: ${sprint.goal}`,
    `Dates: ${sprint.start} to ${sprint.end}. Capacity: ${sprint.capacity} pts.${velocityValue != null ? ` Velocity (last three sprints): ${velocityValue} pts.` : ""}`,
    `Committed at start: ${committed} pts. In scope now: ${inScope} pts. Completed: ${completed} pts.`,
    sprint.closed ? `Closed on ${localDate(sprint.closed.at)}: ${sprint.closed.completed} pts completed, carried over ${sprint.closed.carryOver.join(", ") || "nothing"}.` : "",
    "",
    "## Cards by state",
    "",
    "| State | Cards |",
    "|---|---|",
    ...Object.entries(byState).map(([state, ids]) => `| ${state} | ${ids.sort().join(", ")} |`),
    "",
  ];
  if ((sprint.scope || []).length) {
    lines.push("## Scope changes", "", "| Date | Card | Change | Points |", "|---|---|---|---|");
    for (const e of sprint.scope) lines.push(`| ${localDate(e.at)} | ${e.id} | ${e.change} | ${e.points} |`);
    lines.push("");
  }
  if ((sprint.reestimates || []).length) {
    lines.push("## Re-estimates", "", "| Card | At start | Now |", "|---|---|---|");
    for (const r of sprint.reestimates) lines.push(`| ${r.id} | ${r.from} | ${r.to} |`);
    lines.push("");
  }
  lines.push("## Burndown", "", "| Day | Remaining | Ideal |", "|---|---|---|");
  for (const row of burndown(sprint, cards, asOf)) lines.push(`| ${row.day} | ${row.remaining} | ${row.ideal} |`);
  lines.push("", "Moves made directly in ClickUp are not in the burndown until the lifecycle record catches up; `board --remote` lists them.", "");
  return lines.filter((l, i, a) => !(l === "" && a[i - 1] === "")).join("\n");
}
