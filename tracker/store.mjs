// Tracker files in docs/tracker/: config.json (choices), remote.json (card registry and the queue
// of operations that could not reach the tracker), board.md (generated view) and .lock.

import { closeSync, existsSync, mkdirSync, openSync, readFileSync, renameSync, statSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { STATES } from "./cards.mjs";

// A lock whose process has gone is free at once; one older than this is free even if a process
// with that ID exists, because the ID may have been reused.
const STALE_LOCK_MS = 60 * 60 * 1000;

export function trackerPaths(root) {
  const dir = join(root, "docs", "tracker");
  return {
    dir,
    config: join(dir, "config.json"),
    remote: join(dir, "remote.json"),
    board: join(dir, "board.md"),
    lock: join(dir, ".lock"),
  };
}

export function readJson(path, fallback) {
  if (!existsSync(path)) return fallback;
  return JSON.parse(readFileSync(path, "utf8"));
}

// Write to a temporary file and rename, so an interrupted run never leaves half a file.
export function writeJsonAtomic(path, data) {
  mkdirSync(dirname(path), { recursive: true });
  const temp = `${path}.${process.pid}.tmp`;
  writeFileSync(temp, `${JSON.stringify(data, null, 2)}\n`);
  renameSync(temp, path);
}

export function loadState(paths) {
  const state = readJson(paths.remote, null) || { version: 1, cards: {}, pending: [] };
  state.cards ||= {};
  state.pending ||= [];
  return state;
}

function createLock(path) {
  const fd = openSync(path, "wx");
  writeFileSync(fd, String(process.pid));
  closeSync(fd);
}

function alive(pid) {
  if (!Number.isInteger(pid) || pid <= 0) return false;
  try {
    process.kill(pid, 0);
    return true;
  } catch (error) {
    return error.code === "EPERM";
  }
}

export function acquireLock(paths) {
  mkdirSync(paths.dir, { recursive: true });
  try {
    createLock(paths.lock);
    return true;
  } catch (error) {
    if (error.code !== "EEXIST") throw error;
  }
  let owner = NaN;
  let age = 0;
  try {
    owner = Number.parseInt(readFileSync(paths.lock, "utf8"), 10);
    age = Date.now() - statSync(paths.lock).mtimeMs;
  } catch {
    // Removed while we looked: try once more below.
  }
  if (alive(owner) && age < STALE_LOCK_MS) return false;
  // Rename is atomic: if two processes find the same stale lock, only one rename succeeds.
  const stale = `${paths.lock}.stale.${process.pid}`;
  try {
    renameSync(paths.lock, stale);
    unlinkSync(stale);
  } catch {
    return false;
  }
  try {
    createLock(paths.lock);
    return true;
  } catch {
    return false;
  }
}

// Removes the lock only if this process holds it.
export function releaseLock(paths) {
  try {
    if (Number.parseInt(readFileSync(paths.lock, "utf8"), 10) === process.pid) unlinkSync(paths.lock);
  } catch {
    // Already gone: nothing to release.
  }
}

const STATE_TITLES = {
  backlog: "Backlog",
  ready: "Ready",
  in_progress: "In progress",
  in_review: "In review",
  in_test: "In test",
  ready_for_release: "Ready for release",
  done: "Done",
  blocked: "Blocked",
};

export function renderBoard(state, config) {
  const cards = Object.entries(state.cards);
  const lines = [
    "# Board",
    "",
    `Generated by the adlc-3d tracker from docs/tracker/remote.json. Do not edit; run the tracker instead.`,
    `Tracker: ${config.provider}${config.listId ? ` (List ${config.listId})` : ""}. Content sent: ${config.content || "full"}.`,
    "",
  ];
  if (state.pending.length)
    lines.push(`**${state.pending.length} operation(s) queued** because the tracker could not be reached. The next tracker command retries them.`, "");
  for (const key of STATES) {
    const inState = cards.filter(([, card]) => card.state === key);
    if (!inState.length) continue;
    lines.push(`## ${STATE_TITLES[key]} (${inState.length})`, "", "| Card | Key | Type | Title |", "|---|---|---|---|");
    for (const [id, card] of inState.sort(([a], [b]) => a.localeCompare(b, "en", { numeric: true }))) {
      const keyCell = card.url ? `[${card.key}](${card.url})` : card.key || id;
      lines.push(`| ${id} | ${keyCell} | ${card.kind} | ${String(card.title || "").replace(/\|/g, "/")} |`);
    }
    lines.push("");
  }
  if (!cards.length) lines.push("No cards yet. Run `push` after the stories are written.", "");
  return lines.join("\n");
}
